using System;
using System.Collections.Generic;
using System.Reflection;
using Aoiro;
using Gameplay.Tables;
using UnityEditor;

namespace Gameplay.Editor
{
    public static class ActionGenerator
    {
        private const string OutputPath = "Assets/Gameplay/Scripts/Definition/Action/Generated/ActionResolver.g.cs";
        private const string GeneratedFileMarker = "// Generated by ActionGenerator.";
        private const string MenuPath = "Tools/Gameplay/Generate Action";

        [MenuItem(MenuPath)]
        public static void Generate()
        {
            var content = GenerateContent();
            ResolverGenerationUtility.Write(OutputPath, content, GeneratedFileMarker);
        }

        public static void CheckGenerated()
        {
            ResolverGenerationUtility.Check(OutputPath, GenerateContent(), GeneratedFileMarker, MenuPath);
        }

        private static string GenerateContent()
        {
            var definitions = new HashSet<Type>();
            var items = new List<ResolverTemplateItem>();
            foreach (var resolver in typeof(GameplayArchitecture).Assembly.GetTypes())
            {
                foreach (var attribute in resolver.GetCustomAttributes<ActionResolverAttribute>(false))
                {
                    ResolverGenerationUtility.ValidateBinding(attribute.DefinitionType, resolver, typeof(ActionDef), "Execute", typeof(ICommandContext), definitions);
                    items.Add(new ResolverTemplateItem(attribute.DefinitionType, resolver));
                }
            }
            ResolverGenerationUtility.ValidateCoverage(typeof(ActionDef), definitions);
            items.Sort((left, right) => StringComparer.Ordinal.Compare(left.DefinitionTypeName, right.DefinitionTypeName));
            return ResolverGenerationUtility.Render("ActionResolver", new { Items = items });
        }
    }
}
