using System;
using System.Collections.Generic;
using System.Reflection;
using Aoiro;
using Gameplay.Tables;
using UnityEditor;

namespace Gameplay.Editor
{
    public static class ConditionGenerator
    {
        private const string OutputPath = "Assets/Gameplay/Scripts/Definition/Condition/Generated/ConditionResolver.g.cs";
        private const string GeneratedFileMarker = "// Generated by ConditionGenerator.";
        private const string MenuPath = "Tools/Gameplay/Generate Condition";

        [MenuItem(MenuPath)]
        public static void Generate()
        {
            var content = GenerateContent();
            ResolverGenerationUtility.Write(OutputPath, content, GeneratedFileMarker);
        }

        public static void CheckGenerated()
        {
            ResolverGenerationUtility.Check(OutputPath, GenerateContent(), GeneratedFileMarker, MenuPath);
        }

        private static string GenerateContent()
        {
            var definitions = new HashSet<Type>();
            var items = new List<ConditionResolverTemplateItem>();
            var allowed = ConditionSource.None;
            foreach (ConditionSource source in Enum.GetValues(typeof(ConditionSource)))
            {
                allowed |= source;
            }
            foreach (var resolver in typeof(GameplayArchitecture).Assembly.GetTypes())
            {
                foreach (var attribute in resolver.GetCustomAttributes<ConditionResolverAttribute>(false))
                {
                    if ((attribute.Sources & ~allowed) != 0 || attribute.DefinitionType == typeof(AllConditionDef) || attribute.DefinitionType == typeof(AnyConditionDef))
                    {
                        throw new InvalidOperationException($"Invalid condition sources or reserved composite [{resolver.FullName}].");
                    }

                    ResolverGenerationUtility.ValidateBinding(attribute.DefinitionType, resolver, typeof(ConditionDef), "Evaluate", typeof(IQueryContext), definitions);
                    items.Add(new ConditionResolverTemplateItem(attribute.DefinitionType, resolver, attribute.Sources));
                }
            }
            definitions.Add(typeof(AllConditionDef));
            definitions.Add(typeof(AnyConditionDef));
            ResolverGenerationUtility.ValidateCoverage(typeof(ConditionDef), definitions);
            items.Sort((left, right) => StringComparer.Ordinal.Compare(left.DefinitionTypeName, right.DefinitionTypeName));
            return ResolverGenerationUtility.Render("ConditionResolver", new { Items = items });
        }
    }
}
