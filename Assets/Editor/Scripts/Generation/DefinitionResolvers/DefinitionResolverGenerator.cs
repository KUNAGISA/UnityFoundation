using System;
using System.Collections.Generic;
using System.IO;
using System.Reflection;
using System.Text;
using Scriban;
using UnityEditor;
using UnityEngine;

namespace Gameplay.Editor
{
    internal static class DefinitionResolverGenerator
    {
        private const string TemplateDirectory = "Assets/Editor/Scripts/Generation/DefinitionResolvers/Templates";
        private const string DefinitionDirectory = "Assets/Gameplay/Scripts/Definition";
        private const string GeneratedMarker = "// Generated by DefinitionResolverGenerator.";

        [MenuItem("Tools/Gameplay/Generate Definition Resolvers")]
        public static void GenerateDefinitionResolvers()
        {
            var assembly = typeof(GameplayArchitecture).Assembly;
            var rules = CollectRules(assembly);
            var bindings = CollectBindings(assembly);
            var outputs = new Dictionary<string, string>(StringComparer.OrdinalIgnoreCase);
            var resolverNames = new HashSet<string>(StringComparer.Ordinal);

            foreach (var rule in rules)
            {
                ValidateRule(rule);
                AddOutput(rule, bindings, outputs, resolverNames);
            }

            var paths = new List<string>(outputs.Keys);
            paths.Sort(StringComparer.Ordinal);
            foreach (var path in paths)
            {
                Directory.CreateDirectory(Path.GetDirectoryName(path) ?? string.Empty);
                var content = outputs[path];
                if (!File.Exists(path) || File.ReadAllText(path, Encoding.UTF8) != content)
                {
                    File.WriteAllText(path, content, new UTF8Encoding(false));
                }
            }

            Clean(outputs);
            AssetDatabase.Refresh();
            Debug.Log("Definition resolver generation completed.");
        }

        private static List<GenerateDefinitionResolverAttribute> CollectRules(Assembly assembly)
        {
            var result = new List<GenerateDefinitionResolverAttribute>();
            foreach (var rule in assembly.GetCustomAttributes<GenerateDefinitionResolverAttribute>())
            {
                result.Add(rule);
            }

            if (result.Count == 0)
            {
                throw new InvalidOperationException("No definition resolver generation rules were found.");
            }

            result.Sort((left, right) =>
            {
                var generatedTypeOrder = StringComparer.Ordinal.Compare(left.GeneratedType, right.GeneratedType);
                return generatedTypeOrder != 0 ? generatedTypeOrder : StringComparer.Ordinal.Compare(left.TemplateName, right.TemplateName);
            });
            return result;
        }

        private static List<DefinitionResolverBinding> CollectBindings(Assembly assembly)
        {
            var result = new List<DefinitionResolverBinding>();
            var owners = new Dictionary<Type, Type>();
            foreach (var resolverType in assembly.GetTypes())
            {
                MethodInfo[] methods = null;
                foreach (var attribute in resolverType.GetCustomAttributes<DefinitionResolverAttribute>(false))
                {
                    if (!resolverType.IsClass || !resolverType.IsAbstract || !resolverType.IsSealed)
                    {
                        throw new InvalidOperationException($"Definition resolver [{resolverType.FullName}] must be a static class.");
                    }

                    var definitionType = attribute.DefinitionType;
                    if (!definitionType.IsClass || definitionType.IsAbstract)
                    {
                        throw new InvalidOperationException($"Invalid definition type [{definitionType.FullName}] on [{resolverType.FullName}].");
                    }

                    if (owners.TryGetValue(definitionType, out var owner))
                    {
                        throw new InvalidOperationException($"Duplicate definition resolver [{definitionType.FullName}] on [{owner.FullName}] and [{resolverType.FullName}].");
                    }

                    owners.Add(definitionType, resolverType);
                    if (methods == null)
                    {
                        methods = resolverType.GetMethods(BindingFlags.Public | BindingFlags.Static | BindingFlags.DeclaredOnly);
                    }

                    result.Add(new DefinitionResolverBinding(definitionType, resolverType, methods));
                }
            }

            result.Sort((left, right) => StringComparer.Ordinal.Compare(left.DefinitionType.FullName, right.DefinitionType.FullName));
            return result;
        }

        private static void ValidateRule(GenerateDefinitionResolverAttribute rule)
        {
            if ((rule.GeneratedType.Length > 0 && !IsIdentifier(rule.GeneratedType)) || !rule.DefinitionBaseType.IsClass || rule.DefinitionBaseType.ContainsGenericParameters)
            {
                throw new InvalidOperationException($"Invalid definition resolver generation rule [{rule.GeneratedType}].");
            }

            foreach (var parameterType in rule.RequiredParameterTypes)
            {
                if (parameterType == null || parameterType.IsByRef || parameterType.ContainsGenericParameters)
                {
                    throw new InvalidOperationException($"Invalid required parameter type in [{rule.GeneratedType}].");
                }
            }

            var optionalParameterType = rule.OptionalParameterType;
            if (optionalParameterType != null && (optionalParameterType.IsByRef || optionalParameterType.ContainsGenericParameters))
            {
                throw new InvalidOperationException($"Invalid optional parameter type in [{rule.GeneratedType}].");
            }
        }

        private static List<DefinitionResolverTemplateItem> CollectRuleItems(GenerateDefinitionResolverAttribute rule, IReadOnlyList<DefinitionResolverBinding> bindings)
        {
            var items = new List<DefinitionResolverTemplateItem>();
            foreach (var binding in bindings)
            {
                if (!rule.DefinitionBaseType.IsAssignableFrom(binding.DefinitionType))
                {
                    continue;
                }

                var optionalMethod = rule.OptionalParameterType == null ? null : FindMethod(binding, rule, rule.OptionalParameterType);
                var method = optionalMethod ?? FindMethod(binding, rule, null);
                if (method != null)
                {
                    items.Add(new DefinitionResolverTemplateItem(GetTypeName(binding.DefinitionType), GetTypeName(binding.ResolverType), method.Name, optionalMethod != null));
                }
            }

            return items;
        }

        private static MethodInfo FindMethod(DefinitionResolverBinding binding, GenerateDefinitionResolverAttribute rule, Type optionalParameterType)
        {
            MethodInfo found = null;
            foreach (var method in binding.Methods)
            {
                if (!MatchesMethod(method, binding.DefinitionType, rule, optionalParameterType))
                {
                    continue;
                }

                if (found != null)
                {
                    throw new InvalidOperationException($"Ambiguous resolver methods [{binding.ResolverType.FullName}.{found.Name}] and [{binding.ResolverType.FullName}.{method.Name}] for [{binding.DefinitionType.FullName}].");
                }

                found = method;
            }

            return found;
        }

        private static bool MatchesMethod(MethodInfo method, Type definitionType, GenerateDefinitionResolverAttribute rule, Type optionalParameterType)
        {
            if (method.ContainsGenericParameters || method.ReturnType != rule.ReturnType)
            {
                return false;
            }

            var parameters = method.GetParameters();
            var requiredTypes = rule.RequiredParameterTypes;
            var expectedLength = requiredTypes.Length + 1 + (optionalParameterType == null ? 0 : 1);
            if (parameters.Length != expectedLength || parameters[0].ParameterType != definitionType)
            {
                return false;
            }

            for (var index = 0; index < requiredTypes.Length; index++)
            {
                if (parameters[index + 1].ParameterType != requiredTypes[index])
                {
                    return false;
                }
            }

            if (optionalParameterType != null)
            {
                var optionalParameter = parameters[requiredTypes.Length + 1];
                if (optionalParameter.ParameterType != optionalParameterType.MakeByRefType() || !optionalParameter.IsIn || optionalParameter.IsOut)
                {
                    return false;
                }
            }

            return true;
        }

        private static void AddOutput(GenerateDefinitionResolverAttribute rule, IReadOnlyList<DefinitionResolverBinding> bindings, IDictionary<string, string> outputs, ISet<string> resolverNames)
        {
            var templatePath = GetTemplatePath(rule.TemplateName);
            var directory = GetOutputDirectory(rule);
            var templateTypeName = Path.GetFileNameWithoutExtension(rule.TemplateName);
            if (!IsIdentifier(templateTypeName))
            {
                throw new InvalidOperationException($"Invalid definition resolver template name [{rule.TemplateName}].");
            }

            var resolverName = rule.GeneratedType + templateTypeName;
            if (!resolverNames.Add(resolverName))
            {
                throw new InvalidOperationException($"Duplicate generated resolver type [{resolverName}].");
            }

            var items = CollectRuleItems(rule, bindings);

            var requiredTypeNames = new List<string>();
            foreach (var requiredType in rule.RequiredParameterTypes)
            {
                requiredTypeNames.Add(GetTypeName(requiredType));
            }

            var optionalTypeName = rule.OptionalParameterType == null ? null : GetTypeName(rule.OptionalParameterType);
            var model = new DefinitionResolverTemplateModel(resolverName, GetTypeName(rule.DefinitionBaseType), GetTypeName(rule.ReturnType), requiredTypeNames, optionalTypeName, items);
            var path = directory + "/" + resolverName + ".g.cs";
            if (outputs.ContainsKey(path))
            {
                throw new InvalidOperationException($"Duplicate generated resolver path [{path}].");
            }

            outputs.Add(path, RenderTemplate(templatePath, model));
        }

        private static string GetTemplatePath(string templateName)
        {
            var root = Path.GetFullPath(TemplateDirectory) + Path.DirectorySeparatorChar;
            var path = Path.GetFullPath(Path.Combine(TemplateDirectory, templateName));
            if (!path.StartsWith(root, StringComparison.OrdinalIgnoreCase) || !File.Exists(path))
            {
                throw new InvalidOperationException($"Invalid definition resolver template [{templateName}].");
            }

            return path;
        }

        private static string GetOutputDirectory(GenerateDefinitionResolverAttribute rule)
        {
            var baseName = rule.DefinitionBaseType.Name;
            if (baseName.EndsWith("Def", StringComparison.Ordinal))
            {
                baseName = baseName.Substring(0, baseName.Length - "Def".Length);
            }

            var directory = string.IsNullOrWhiteSpace(rule.OutputDirectory)
                ? DefinitionDirectory + "/" + baseName + "/Generated"
                : rule.OutputDirectory.Replace('\\', '/').TrimEnd('/');
            foreach (var segment in directory.Split('/'))
            {
                if (string.IsNullOrEmpty(segment) || segment == "." || segment == "..")
                {
                    throw new InvalidOperationException($"Invalid definition resolver output directory [{directory}].");
                }
            }

            var assetsRoot = Path.GetFullPath("Assets") + Path.DirectorySeparatorChar;
            var fullPath = Path.GetFullPath(directory);
            if (!fullPath.StartsWith(assetsRoot, StringComparison.OrdinalIgnoreCase) || Path.IsPathRooted(directory))
            {
                throw new InvalidOperationException($"Invalid definition resolver output directory [{directory}].");
            }

            return directory;
        }

        private static string GetTypeName(Type type)
        {
            if (type == typeof(void))
            {
                return "void";
            }

            if (type.IsArray)
            {
                return GetTypeName(type.GetElementType()) + "[" + new string(',', type.GetArrayRank() - 1) + "]";
            }

            if (type.IsByRef || type.IsPointer || type.ContainsGenericParameters || type.FullName == null)
            {
                throw new InvalidOperationException($"Unsupported resolver signature type [{type}].");
            }

            if (!type.IsGenericType)
            {
                return "global::" + type.FullName.Replace('+', '.');
            }

            var segments = type.GetGenericTypeDefinition().FullName.Split('+');
            var arguments = type.GetGenericArguments();
            var argumentIndex = 0;
            var name = new StringBuilder("global::");
            for (var segmentIndex = 0; segmentIndex < segments.Length; segmentIndex++)
            {
                if (segmentIndex > 0)
                {
                    name.Append('.');
                }

                var segment = segments[segmentIndex];
                var marker = segment.LastIndexOf('`');
                if (marker < 0)
                {
                    name.Append(segment);
                    continue;
                }

                name.Append(segment.Substring(0, marker));
                var count = int.Parse(segment.Substring(marker + 1));
                name.Append('<');
                for (var index = 0; index < count; index++)
                {
                    if (index > 0)
                    {
                        name.Append(", ");
                    }

                    name.Append(GetTypeName(arguments[argumentIndex++]));
                }

                name.Append('>');
            }

            return name.ToString();
        }

        private static bool IsIdentifier(string value)
        {
            if (string.IsNullOrEmpty(value) || !(char.IsLetter(value[0]) || value[0] == '_'))
            {
                return false;
            }

            for (var index = 1; index < value.Length; index++)
            {
                if (!char.IsLetterOrDigit(value[index]) && value[index] != '_')
                {
                    return false;
                }
            }

            return true;
        }

        private static string RenderTemplate(string templatePath, object model)
        {
            var template = Template.Parse(File.ReadAllText(templatePath, Encoding.UTF8), templatePath);
            if (template.HasErrors)
            {
                throw new InvalidOperationException($"Failed to parse template [{templatePath}]: {string.Join(", ", template.Messages)}");
            }

            return template.Render(model, member => member.Name);
        }

        private static void Clean(IReadOnlyDictionary<string, string> outputs)
        {
            foreach (var path in Directory.GetFiles("Assets", "*.g.cs", SearchOption.AllDirectories))
            {
                var normalizedPath = path.Replace('\\', '/');
                if (outputs.ContainsKey(normalizedPath))
                {
                    continue;
                }

                var generatedByResolver = false;
                using (var reader = new StreamReader(path, Encoding.UTF8))
                {
                    for (var line = 0; line < 10 && !reader.EndOfStream; line++)
                    {
                        if (reader.ReadLine() == GeneratedMarker)
                        {
                            generatedByResolver = true;
                            break;
                        }
                    }
                }

                if (generatedByResolver)
                {
                    AssetDatabase.DeleteAsset(normalizedPath);
                }
            }
        }
    }
}
